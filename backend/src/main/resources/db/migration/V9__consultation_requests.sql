CREATE TABLE CONSULTATION_REQUEST (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    REQUIREMENT_ID NUMBER NOT NULL,
    EXPERT_ID NUMBER NOT NULL,
    MESSAGE VARCHAR2(2000 CHAR),
    REQUESTED_START_DATE DATE,
    ESTIMATED_HOURS NUMBER(6,1),
    PROPOSED_RATE NUMBER(12,2),
    CURRENCY_CODE CHAR(3 CHAR) DEFAULT 'USD' NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CONSULT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT FK_CONSULT_REQUIREMENT FOREIGN KEY (REQUIREMENT_ID) REFERENCES CUSTOMER_REQUIREMENT(REQUIREMENT_ID),
    CONSTRAINT FK_CONSULT_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT CK_CONSULT_STATUS CHECK (STATUS IN ('PENDING','ACCEPTED','REJECTED','CANCELLED')),
    CONSTRAINT CK_CONSULT_HOURS CHECK (ESTIMATED_HOURS IS NULL OR ESTIMATED_HOURS > 0),
    CONSTRAINT CK_CONSULT_RATE CHECK (PROPOSED_RATE IS NULL OR PROPOSED_RATE >= 0)
);

CREATE INDEX IX_CONSULT_CUSTOMER ON CONSULTATION_REQUEST(CUSTOMER_ID);
CREATE INDEX IX_CONSULT_REQUIREMENT ON CONSULTATION_REQUEST(REQUIREMENT_ID);
CREATE INDEX IX_CONSULT_EXPERT ON CONSULTATION_REQUEST(EXPERT_ID);
CREATE INDEX IX_CONSULT_STATUS ON CONSULTATION_REQUEST(STATUS);
