CREATE TABLE FINANCIAL_LEDGER_ENTRY (
    LEDGER_ENTRY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    EXPERT_ID NUMBER,
    ENGAGEMENT_ID NUMBER,
    INVOICE_ID NUMBER,
    PAYMENT_ID NUMBER,
    SETTLEMENT_ID NUMBER,
    REPLACEMENT_REQUEST_ID NUMBER,
    PARENT_LEDGER_ENTRY_ID NUMBER,
    ENTRY_TYPE VARCHAR2(40 CHAR) NOT NULL,
    ENTRY_DIRECTION VARCHAR2(10 CHAR) NOT NULL,
    AMOUNT NUMBER(14,2) NOT NULL,
    CURRENCY_CODE VARCHAR2(3 CHAR) NOT NULL,
    SOURCE_TYPE VARCHAR2(40 CHAR) NOT NULL,
    SOURCE_ID VARCHAR2(100 CHAR) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(180 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(2000 CHAR) NOT NULL,
    OCCURRED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(150 CHAR),
    CONSTRAINT UK_LEDGER_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT FK_LEDGER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT FK_LEDGER_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT FK_LEDGER_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT FK_LEDGER_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICE(INVOICE_ID),
    CONSTRAINT FK_LEDGER_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT_TRANSACTION(PAYMENT_ID),
    CONSTRAINT FK_LEDGER_SETTLEMENT FOREIGN KEY (SETTLEMENT_ID) REFERENCES SETTLEMENT(SETTLEMENT_ID),
    CONSTRAINT FK_LEDGER_REPLACEMENT FOREIGN KEY (REPLACEMENT_REQUEST_ID) REFERENCES EXPERT_REPLACEMENT_REQUEST(REPLACEMENT_REQUEST_ID),
    CONSTRAINT FK_LEDGER_PARENT FOREIGN KEY (PARENT_LEDGER_ENTRY_ID) REFERENCES FINANCIAL_LEDGER_ENTRY(LEDGER_ENTRY_ID),
    CONSTRAINT CK_LEDGER_DIRECTION CHECK (ENTRY_DIRECTION IN ('DEBIT','CREDIT')),
    CONSTRAINT CK_LEDGER_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_LEDGER_TYPE CHECK (ENTRY_TYPE IN ('INVOICE_CHARGE','CUSTOMER_PAYMENT','PAYMENT_REFUND','CUSTOMER_CREDIT','CUSTOMER_REFUND','EXPERT_EARNING','EXPERT_PAYOUT','PLATFORM_FEE','REPLACEMENT_ADJUSTMENT'))
);
CREATE INDEX IX_LEDGER_CUSTOMER ON FINANCIAL_LEDGER_ENTRY(CUSTOMER_ID, OCCURRED_AT);
CREATE INDEX IX_LEDGER_EXPERT ON FINANCIAL_LEDGER_ENTRY(EXPERT_ID, OCCURRED_AT);
CREATE INDEX IX_LEDGER_ENGAGEMENT ON FINANCIAL_LEDGER_ENTRY(ENGAGEMENT_ID, OCCURRED_AT);
CREATE INDEX IX_LEDGER_SOURCE ON FINANCIAL_LEDGER_ENTRY(SOURCE_TYPE, SOURCE_ID);
CREATE INDEX IX_LEDGER_TYPE ON FINANCIAL_LEDGER_ENTRY(ENTRY_TYPE, OCCURRED_AT);
