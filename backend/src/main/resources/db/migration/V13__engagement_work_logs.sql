CREATE TABLE ENGAGEMENT_WORK_LOG (
    WORK_LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    WORK_DATE DATE NOT NULL,
    HOURS NUMBER(5,2) NOT NULL,
    DESCRIPTION VARCHAR2(2000 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_WORK_LOG_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT CK_WORK_LOG_HOURS CHECK (HOURS > 0 AND HOURS <= 24)
);

CREATE INDEX IX_WORK_LOG_ENGAGEMENT ON ENGAGEMENT_WORK_LOG(ENGAGEMENT_ID);
CREATE INDEX IX_WORK_LOG_DATE ON ENGAGEMENT_WORK_LOG(WORK_DATE);
