CREATE TABLE APP_USER (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(320 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    ROLE VARCHAR2(30 CHAR) NOT NULL,
    CUSTOMER_ID NUMBER,
    EXPERT_ID NUMBER,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_APP_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT FK_USER_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT CK_APP_USER_ROLE CHECK (ROLE IN ('CUSTOMER','EXPERT','ADMIN')),
    CONSTRAINT CK_APP_USER_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','LOCKED')),
    CONSTRAINT CK_APP_USER_OWNER CHECK (
        (ROLE = 'CUSTOMER' AND CUSTOMER_ID IS NOT NULL AND EXPERT_ID IS NULL)
        OR (ROLE = 'EXPERT' AND EXPERT_ID IS NOT NULL AND CUSTOMER_ID IS NULL)
        OR (ROLE = 'ADMIN' AND CUSTOMER_ID IS NULL AND EXPERT_ID IS NULL)
    )
);

CREATE INDEX IX_APP_USER_CUSTOMER ON APP_USER(CUSTOMER_ID);
CREATE INDEX IX_APP_USER_EXPERT ON APP_USER(EXPERT_ID);
CREATE INDEX IX_APP_USER_ROLE ON APP_USER(ROLE);
