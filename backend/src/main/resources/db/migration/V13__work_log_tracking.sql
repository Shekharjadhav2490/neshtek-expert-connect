CREATE TABLE WORK_LOG (
    WORK_LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    WORK_DATE DATE NOT NULL,
    HOURS NUMBER(8,2) NOT NULL,
    DESCRIPTION VARCHAR2(2000 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    SUBMITTED_AT TIMESTAMP,
    REVIEWED_AT TIMESTAMP,
    REVIEWER_COMMENT VARCHAR2(1000 CHAR),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_WORK_LOG_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT CK_WORK_LOG_HOURS CHECK (HOURS > 0 AND HOURS <= 24),
    CONSTRAINT CK_WORK_LOG_STATUS CHECK (STATUS IN ('DRAFT','SUBMITTED','APPROVED','REJECTED'))
);
CREATE INDEX IX_WORK_LOG_ENGAGEMENT ON WORK_LOG(ENGAGEMENT_ID);
CREATE INDEX IX_WORK_LOG_STATUS ON WORK_LOG(STATUS);
CREATE INDEX IX_WORK_LOG_DATE ON WORK_LOG(WORK_DATE);
