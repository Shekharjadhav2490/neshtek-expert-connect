CREATE TABLE SETTLEMENT (
    SETTLEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    EXPERT_ID NUMBER NOT NULL,
    APPROVED_HOURS NUMBER(10,2) NOT NULL,
    HOURLY_RATE NUMBER(12,2) NOT NULL,
    GROSS_AMOUNT NUMBER(14,2) NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'REQUESTED' NOT NULL,
    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    APPROVED_AT TIMESTAMP,
    PAID_AT TIMESTAMP,
    REJECTED_AT TIMESTAMP,
    ADMIN_COMMENT VARCHAR2(1000 CHAR),
    PAYMENT_REFERENCE VARCHAR2(200 CHAR),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_SETTLEMENT_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT FK_SETTLEMENT_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT CK_SETTLEMENT_STATUS CHECK (STATUS IN ('REQUESTED','APPROVED_FOR_PAYOUT','PAID','REJECTED')),
    CONSTRAINT CK_SETTLEMENT_HOURS CHECK (APPROVED_HOURS > 0),
    CONSTRAINT CK_SETTLEMENT_AMOUNT CHECK (GROSS_AMOUNT > 0)
);

CREATE INDEX IX_SETTLEMENT_EXPERT ON SETTLEMENT(EXPERT_ID);
CREATE INDEX IX_SETTLEMENT_ENGAGEMENT ON SETTLEMENT(ENGAGEMENT_ID);
CREATE INDEX IX_SETTLEMENT_STATUS ON SETTLEMENT(STATUS);
CREATE INDEX IX_SETTLEMENT_REQUESTED_AT ON SETTLEMENT(REQUESTED_AT);
