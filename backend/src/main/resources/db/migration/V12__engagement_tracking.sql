CREATE TABLE ENGAGEMENT (
    ENGAGEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONSULTATION_REQUEST_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    EXPERT_ID NUMBER NOT NULL,
    REQUIREMENT_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'READY' NOT NULL,
    STARTED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    CANCELLED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_ENGAGEMENT_CONSULT UNIQUE (CONSULTATION_REQUEST_ID),
    CONSTRAINT FK_ENGAGEMENT_CONSULT FOREIGN KEY (CONSULTATION_REQUEST_ID) REFERENCES CONSULTATION_REQUEST(REQUEST_ID),
    CONSTRAINT FK_ENGAGEMENT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT FK_ENGAGEMENT_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT FK_ENGAGEMENT_REQUIREMENT FOREIGN KEY (REQUIREMENT_ID) REFERENCES CUSTOMER_REQUIREMENT(REQUIREMENT_ID),
    CONSTRAINT CK_ENGAGEMENT_STATUS CHECK (STATUS IN ('READY','ACTIVE','COMPLETED','CANCELLED'))
);

CREATE INDEX IX_ENGAGEMENT_CUSTOMER ON ENGAGEMENT(CUSTOMER_ID);
CREATE INDEX IX_ENGAGEMENT_EXPERT ON ENGAGEMENT(EXPERT_ID);
CREATE INDEX IX_ENGAGEMENT_STATUS ON ENGAGEMENT(STATUS);
