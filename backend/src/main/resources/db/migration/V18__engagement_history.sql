CREATE TABLE ENGAGEMENT_HISTORY (
    HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    ACTION VARCHAR2(50 CHAR) NOT NULL,
    FROM_STATUS VARCHAR2(20 CHAR),
    TO_STATUS VARCHAR2(20 CHAR),
    ACTOR_USER_ID NUMBER,
    ACTOR_ROLE VARCHAR2(30 CHAR),
    ACTOR_NAME VARCHAR2(250 CHAR),
    REASON VARCHAR2(1000 CHAR),
    OCCURRED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ENG_HISTORY_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ENG_HISTORY_USER FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER(USER_ID)
);

CREATE INDEX IX_ENG_HISTORY_ENGAGEMENT ON ENGAGEMENT_HISTORY(ENGAGEMENT_ID, OCCURRED_AT DESC);
CREATE INDEX IX_ENG_HISTORY_ACTOR ON ENGAGEMENT_HISTORY(ACTOR_USER_ID);
