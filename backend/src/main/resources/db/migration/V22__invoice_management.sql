CREATE TABLE INVOICE (
    INVOICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER VARCHAR2(40 CHAR) NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    ENGAGEMENT_ID NUMBER NOT NULL,
    INVOICE_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
    DUE_DATE DATE,
    CURRENCY_CODE VARCHAR2(3 CHAR) NOT NULL,
    SUBTOTAL_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    TAX_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    PAID_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'DRAFT' NOT NULL,
    NOTES VARCHAR2(2000 CHAR),
    ISSUED_AT TIMESTAMP,
    PAID_AT TIMESTAMP,
    CANCELLED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_INVOICE_NUMBER UNIQUE (INVOICE_NUMBER),
    CONSTRAINT FK_INVOICE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT FK_INVOICE_ENGAGEMENT FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT CK_INVOICE_STATUS CHECK (STATUS IN ('DRAFT','ISSUED','PARTIALLY_PAID','PAID','OVERDUE','CANCELLED','REFUNDED')),
    CONSTRAINT CK_INVOICE_AMOUNTS CHECK (SUBTOTAL_AMOUNT >= 0 AND TAX_AMOUNT >= 0 AND TOTAL_AMOUNT >= 0 AND PAID_AMOUNT >= 0 AND PAID_AMOUNT <= TOTAL_AMOUNT)
);
CREATE INDEX IX_INVOICE_CUSTOMER ON INVOICE(CUSTOMER_ID);
CREATE INDEX IX_INVOICE_ENGAGEMENT ON INVOICE(ENGAGEMENT_ID);
CREATE INDEX IX_INVOICE_STATUS ON INVOICE(STATUS);
CREATE INDEX IX_INVOICE_DUE_DATE ON INVOICE(DUE_DATE);
