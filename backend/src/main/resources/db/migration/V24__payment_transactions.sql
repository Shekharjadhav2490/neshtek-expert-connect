CREATE TABLE PAYMENT_TRANSACTION (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_ID NUMBER NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(100 CHAR) NOT NULL,
    PAYMENT_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
    AMOUNT NUMBER(14,2) NOT NULL,
    CURRENCY_CODE VARCHAR2(3 CHAR) NOT NULL,
    PAYMENT_METHOD VARCHAR2(30 CHAR) NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'SUCCESS' NOT NULL,
    NOTES VARCHAR2(1000 CHAR),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_PAYMENT_REFERENCE UNIQUE (PAYMENT_REFERENCE),
    CONSTRAINT FK_PAYMENT_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICE(INVOICE_ID),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('SUCCESS','PENDING','FAILED','REFUNDED')),
    CONSTRAINT CK_PAYMENT_METHOD CHECK (PAYMENT_METHOD IN ('BANK_TRANSFER','CARD','UPI','CASH','OTHER'))
);
CREATE INDEX IX_PAYMENT_INVOICE ON PAYMENT_TRANSACTION(INVOICE_ID);
CREATE INDEX IX_PAYMENT_DATE ON PAYMENT_TRANSACTION(PAYMENT_DATE);
CREATE INDEX IX_PAYMENT_STATUS ON PAYMENT_TRANSACTION(STATUS);
