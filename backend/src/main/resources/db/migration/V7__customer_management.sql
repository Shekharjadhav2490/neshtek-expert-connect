CREATE TABLE CUSTOMER (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_NAME VARCHAR2(200) NOT NULL,
    CONTACT_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(320) NOT NULL,
    PHONE VARCHAR2(30),
    COUNTRY VARCHAR2(100),
    CITY VARCHAR2(100),
    TIMEZONE VARCHAR2(100),
    INDUSTRY VARCHAR2(150),
    COMPANY_SIZE VARCHAR2(50),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CUSTOMER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CUSTOMER_STATUS CHECK (STATUS IN ('ACTIVE','SUSPENDED'))
);

CREATE INDEX IX_CUSTOMER_STATUS ON CUSTOMER(STATUS);
CREATE INDEX IX_CUSTOMER_COMPANY ON CUSTOMER(COMPANY_NAME);
