CREATE TABLE CUSTOMER_REQUIREMENT (
    REQUIREMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_NAME VARCHAR2(200) NOT NULL,
    CONTACT_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(320) NOT NULL,
    PHONE VARCHAR2(30),
    COUNTRY VARCHAR2(100),
    CITY VARCHAR2(100),
    TITLE VARCHAR2(250) NOT NULL,
    DESCRIPTION CLOB NOT NULL,
    TECHNOLOGY VARCHAR2(150),
    REQUIRED_EXPERIENCE_YEARS NUMBER(4,1),
    ESTIMATED_HOURS NUMBER(6,1),
    PREFERRED_START_DATE DATE,
    PRIORITY VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    BUDGET NUMBER(12,2),
    CURRENCY_CODE CHAR(3) DEFAULT 'USD' NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'SUBMITTED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CUSTOMER_REQ_PRIORITY CHECK (PRIORITY IN ('LOW','MEDIUM','HIGH','URGENT')),
    CONSTRAINT CK_CUSTOMER_REQ_STATUS CHECK (STATUS IN ('DRAFT','SUBMITTED','ANALYZING','MATCHED','EXPERT_SELECTED','CONSULTATION','COMPLETED','CANCELLED')),
    CONSTRAINT CK_CUSTOMER_REQ_HOURS CHECK (ESTIMATED_HOURS IS NULL OR ESTIMATED_HOURS > 0),
    CONSTRAINT CK_CUSTOMER_REQ_BUDGET CHECK (BUDGET IS NULL OR BUDGET >= 0)
);

CREATE TABLE CUSTOMER_REQUIREMENT_SKILL (
    REQUIREMENT_SKILL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUIREMENT_ID NUMBER NOT NULL,
    SKILL_NAME VARCHAR2(150) NOT NULL,
    PRIORITY_ORDER NUMBER(3) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_REQ_SKILL_REQUIREMENT FOREIGN KEY (REQUIREMENT_ID) REFERENCES CUSTOMER_REQUIREMENT(REQUIREMENT_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_REQ_SKILL UNIQUE (REQUIREMENT_ID, SKILL_NAME)
);

CREATE INDEX IX_REQ_STATUS ON CUSTOMER_REQUIREMENT(STATUS);
CREATE INDEX IX_REQ_TECHNOLOGY ON CUSTOMER_REQUIREMENT(TECHNOLOGY);
CREATE INDEX IX_REQ_CREATED_AT ON CUSTOMER_REQUIREMENT(CREATED_AT);
CREATE INDEX IX_REQ_SKILL_NAME ON CUSTOMER_REQUIREMENT_SKILL(SKILL_NAME);
