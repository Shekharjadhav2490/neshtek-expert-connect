CREATE TABLE EXPERT_REPLACEMENT_REQUEST (
    REPLACEMENT_REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    CURRENT_EXPERT_ID NUMBER NOT NULL,
    REQUESTED_BY_USER_ID NUMBER NOT NULL,
    REASON_CODE VARCHAR2(40 CHAR) NOT NULL,
    COMMENTS VARCHAR2(2000 CHAR) NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'REQUESTED' NOT NULL,
    WORK_CUTOFF_AT TIMESTAMP,
    REVIEWED_BY_USER_ID NUMBER,
    REVIEWER_COMMENT VARCHAR2(2000 CHAR),
    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_REPL_REQ_ENG FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT FK_REPL_REQ_EXPERT FOREIGN KEY (CURRENT_EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT FK_REPL_REQ_REQUESTER FOREIGN KEY (REQUESTED_BY_USER_ID) REFERENCES APP_USER(USER_ID),
    CONSTRAINT FK_REPL_REQ_REVIEWER FOREIGN KEY (REVIEWED_BY_USER_ID) REFERENCES APP_USER(USER_ID),
    CONSTRAINT CK_REPL_REQ_STATUS CHECK (STATUS IN ('REQUESTED','APPROVED','REJECTED','CANCELLED')),
    CONSTRAINT CK_REPL_REQ_REASON CHECK (REASON_CODE IN ('SKILLS_MISMATCH','QUALITY_ISSUE','AVAILABILITY','COMMUNICATION','REQUIREMENT_CHANGED','EXPERT_UNAVAILABLE','OTHER'))
);

CREATE UNIQUE INDEX UX_REPL_REQ_OPEN ON EXPERT_REPLACEMENT_REQUEST(
    CASE WHEN STATUS = 'REQUESTED' THEN ENGAGEMENT_ID ELSE NULL END
);

CREATE INDEX IX_REPL_REQ_CUSTOMER ON EXPERT_REPLACEMENT_REQUEST(ENGAGEMENT_ID, REQUESTED_AT DESC);
CREATE INDEX IX_REPL_REQ_EXPERT ON EXPERT_REPLACEMENT_REQUEST(CURRENT_EXPERT_ID, REQUESTED_AT DESC);

CREATE TABLE EXPERT_ASSIGNMENT_HISTORY (
    ASSIGNMENT_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENGAGEMENT_ID NUMBER NOT NULL,
    EXPERT_ID NUMBER NOT NULL,
    ACTION VARCHAR2(40 CHAR) NOT NULL,
    EFFECTIVE_FROM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EFFECTIVE_TO TIMESTAMP,
    REASON VARCHAR2(2000 CHAR),
    ACTOR_USER_ID NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ASSIGN_HIST_ENG FOREIGN KEY (ENGAGEMENT_ID) REFERENCES ENGAGEMENT(ENGAGEMENT_ID),
    CONSTRAINT FK_ASSIGN_HIST_EXPERT FOREIGN KEY (EXPERT_ID) REFERENCES EXPERT(EXPERT_ID),
    CONSTRAINT FK_ASSIGN_HIST_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER(USER_ID),
    CONSTRAINT CK_ASSIGN_HIST_ACTION CHECK (ACTION IN ('ASSIGNED','REPLACEMENT_REQUESTED','REPLACED','REMOVED'))
);

CREATE INDEX IX_ASSIGN_HIST_ENG ON EXPERT_ASSIGNMENT_HISTORY(ENGAGEMENT_ID, EFFECTIVE_FROM DESC);

CREATE TABLE REPLACEMENT_FINANCIAL_RECONCILIATION (
    RECONCILIATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPLACEMENT_REQUEST_ID NUMBER NOT NULL UNIQUE,
    APPROVED_HOURS NUMBER(10,2) DEFAULT 0 NOT NULL,
    ELIGIBLE_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    PAID_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    BALANCE_DUE NUMBER(14,2) DEFAULT 0 NOT NULL,
    REFUND_OR_CREDIT_DUE NUMBER(14,2) DEFAULT 0 NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    CALCULATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NOTES VARCHAR2(2000 CHAR),
    CONSTRAINT FK_RECON_REPL FOREIGN KEY (REPLACEMENT_REQUEST_ID) REFERENCES EXPERT_REPLACEMENT_REQUEST(REPLACEMENT_REQUEST_ID)
);

INSERT INTO EXPERT_ASSIGNMENT_HISTORY (ENGAGEMENT_ID, EXPERT_ID, ACTION, EFFECTIVE_FROM, REASON)
SELECT e.ENGAGEMENT_ID, e.EXPERT_ID, 'ASSIGNED', e.CREATED_AT, 'Initial engagement assignment'
FROM ENGAGEMENT e
WHERE NOT EXISTS (
    SELECT 1 FROM EXPERT_ASSIGNMENT_HISTORY h WHERE h.ENGAGEMENT_ID = e.ENGAGEMENT_ID
);
